-- ── FORMAPAGO ─────────────────────────────────────────────
CREATE TABLE FORMAPAGO (
    IDFORMAPAGO  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRIPCION  VARCHAR2(30) NOT NULL
);

-- ── PAGOCONTRATO ──────────────────────────────────────────
CREATE TABLE PAGOCONTRATO (
    IDPAGOCONTRATO  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IDCONTRATO      NUMBER NOT NULL,
    IDFORMAPAGO     NUMBER NOT NULL,
    FECHAPAGO       DATE NOT NULL,
    VALOR           NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_PAGOCONTRATO_CONTRATO   FOREIGN KEY (IDCONTRATO)  REFERENCES CONTRATO(IDCONTRATO),
    CONSTRAINT FK_PAGOCONTRATO_FORMAPAGO  FOREIGN KEY (IDFORMAPAGO) REFERENCES FORMAPAGO(IDFORMAPAGO)
);
